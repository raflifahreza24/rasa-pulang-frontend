/**
 * Helper pembuat path gambar produk yang terpusat.
 */
export const getProductImagePath = (imageKey, extension = 'webp') => {
  return `/images/rasa-pulang/products/${imageKey}.${extension}`;
};

/**
 * Mencari produk berdasarkan slug atau id
 */
export const findProductBySlug = (slug) => {
  if (!slug) return null;
  const cleanSlug = slug.toLowerCase().trim();
  return productsData.find((p) => {
    return (
      p.slug === cleanSlug ||
      p.slug === cleanSlug.replace(/-250-g$/, '') ||
      p.slug.replace(/-250-g$/, '') === cleanSlug ||
      p.imageKey === cleanSlug ||
      String(p.id) === cleanSlug
    );
  }) || null;
};
